SYSTEM_PROMPT = """You are a stock market assistant. You have tools to fetch historical
data, live prices, technical indicators, a simple next-day price prediction, and a
rule-based buy/hold/sell suggestion.

Rules:
- Always use tools to get real data rather than guessing numbers.
- When giving a suggestion, briefly explain the reasoning behind it in plain language.
- Always end any buy/hold/sell suggestion with a short disclaimer that this is not
  financial advice and is based on limited historical data.
- If a tool returns an error, tell the user clearly instead of making up data.
"""


# ----------------------------------------------------------------------------
# Agent loop
# ----------------------------------------------------------------------------

def run_agent(user_message: str, max_turns: int = 5) -> str:
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_message}
    ]

    for _ in range(max_turns):
        response = client.chat.completions.create(
            model=MODEL,
            max_tokens=1024,
            tools=TOOL_DEFINITIONS,
            messages=messages
        )

        choice = response.choices[0]
        msg = choice.message

        if not msg.tool_calls:
            # Final text answer
            return msg.content or ""

        # Append assistant's tool-call turn to the conversation
        messages.append({
            "role": "assistant",
            "content": msg.content,
            "tool_calls": msg.tool_calls
        })

        # Execute every tool call in this turn
        for tool_call in msg.tool_calls:
            func = TOOL_FUNCTIONS.get(tool_call.function.name)
            try:
                args = json.loads(tool_call.function.arguments)
            except json.JSONDecodeError:
                args = {}

            if func is None:
                result = {"error": f"Unknown tool: {tool_call.function.name}"}
            else:
                try:
                    result = func(**args)
                except Exception as e:
                    result = {"error": f"Tool execution failed: {str(e)}"}

            messages.append({
                "role": "tool",
                "tool_call_id": tool_call.id,
                "name": tool_call.function.name,
                "content": json.dumps(result)
            })

    return "Reached max turns without a final answer — try a simpler question."


